const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium } = require(process.env.TEDX_PLAYWRIGHT_PATH || 'C:/Users/david/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
;(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true})
  const evidence={target:'local production preview 4173 with no provider configuration',checks:[],errors:[],externalRequests:[]}
  try{
    const page=await browser.newPage({viewport:{width:1280,height:900}})
    page.on('pageerror',e=>evidence.errors.push(e.message))
    page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:'))evidence.externalRequests.push(r.url())})
    await page.goto('http://127.0.0.1:4173/tasks')
    await page.getByRole('heading',{name:'Setup needed',exact:true}).waitFor()
    assert(new URL(page.url()).pathname==='/login')
    assert.equal(await page.getByRole('navigation').count(),0)
    await page.evaluate(()=>document.fonts.ready)
    await page.screenshot({path:'docs/build/evidence/P04-login.png',fullPage:true})
    await page.setViewportSize({width:320,height:740})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),320)
    await page.screenshot({path:'docs/build/evidence/P04-login-mobile.png',fullPage:true})
    evidence.checks.push('P04_A2: direct protected route redirects to login; no protected navigation; 320px reflow')
    await page.goto('http://127.0.0.1:4173/preview')
    await page.getByRole('heading',{name:'Page not found',exact:true}).waitFor()
    evidence.checks.push('Production has no development /preview route')
    await page.goto('http://127.0.0.1:4173/auth/callback?error=access_denied&error_description=private-test-diagnostic')
    await page.getByRole('heading',{name:'Sign-in could not be completed',exact:true}).waitFor()
    assert.equal(new URL(page.url()).search,'')
    assert(!(await page.locator('body').textContent()).includes('private-test-diagnostic'))
    const recovery=page.getByRole('link',{name:'Start sign-in again'})
    const box=await recovery.boundingBox();assert(box.width>=44 && box.height>=44)
    await recovery.click()
    await page.getByRole('heading',{name:'Setup needed',exact:true}).waitFor()
    evidence.checks.push('P04_A3: rejected callback strips URL details, provides real recovery; no live Google result claimed')
    await page.goto('http://127.0.0.1:5173/preview')
    await page.getByRole('heading',{name:'Overview',exact:true}).waitFor()
    await page.setViewportSize({width:1280,height:900})
    await page.screenshot({path:'docs/build/evidence/P04-shell-preview.png',fullPage:true})
    assert.deepEqual(evidence.errors,[]);assert.deepEqual(evidence.externalRequests,[])
    fs.writeFileSync('docs/build/evidence/P04-browser.json',JSON.stringify(evidence,null,2)+'\n')
    console.log(JSON.stringify(evidence,null,2))
  }finally{await browser.close()}
})().catch(e=>{console.error(e.message);process.exitCode=1})
